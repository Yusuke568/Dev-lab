-- ============================================================================
-- 上長からのお知らせ（何度実行しても安全）
--   承認権限を持つ人が、組織図で自分が承認者になっている部署（とその下の部署）のメンバーに
--   自由な文章のお知らせを出す。勤怠画面の「ステータス通知」に表示する。
--   department_id の部署と、その下の部署に所属する社員に表示される。
-- ============================================================================

CREATE TABLE IF NOT EXISTS notice (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_staff_id  integer NOT NULL,
    department_id    integer NOT NULL REFERENCES department (id),
    body             text NOT NULL,
    expires_on       date,                                  -- この日まで表示（なければずっと）
    created_at       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_notice_department ON notice (department_id);
CREATE INDEX IF NOT EXISTS idx_notice_author ON notice (author_staff_id);
