-- 社員の期間（開始日〜終了日、両端を含む）の勤怠。月の画面と違い、足りない日の行は作らない
select 
STAFF_ID
,WORK_DATE
,WORK_WEEK
,CORRECTION_ID
,JOB_FROM_TIME
,JOB_TO_TIME
,CORRECTION_US_TIME
,CORRECTION_MID_TIME
,INDIRECT_TIME
,TOTAL_WORK_TIME
,TOTAL_DIRECT_WORK_TIME
,OVERTIME
,ABSTRACT_ID
,REMARKS
,APPROVAL_STATUS
from work_month_table
where STAFF_ID = ?
AND WORK_DATE >= ?
AND WORK_DATE <= ?
ORDER BY WORK_DATE;